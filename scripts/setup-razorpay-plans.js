// Setup Razorpay Subscription Plans
const Razorpay = require('razorpay')
require('dotenv').config({ path: '../.env.local' })

const razorpay = new Razorpay({
  key_id: process.env.RAZORPAY_KEY_ID,
  key_secret: process.env.RAZORPAY_KEY_SECRET,
})

async function setupPlans() {
  console.log('🚀 Setting up Razorpay subscription plans...\n')

  try {
    // Create Founder Special Plan - ₹999/month
    const founderPlan = await razorpay.plans.create({
      period: 'monthly',
      interval: 1,
      item: {
        name: 'BlogCraft AI - Founder Special',
        description: 'Unlimited SEO-optimized blog posts generated by AI',
        amount: 99900, // ₹999 in paise
        currency: 'INR',
      },
      notes: {
        plan_type: 'founder',
        features: 'unlimited_blogs,priority_support,early_access',
      },
    })

    console.log('✅ Founder Special Plan created:')
    console.log(`   Plan ID: ${founderPlan.id}`)
    console.log(`   Amount: ₹${founderPlan.item.amount / 100}/month`)
    console.log(`   Period: ${founderPlan.period}`)
    console.log()

    // Create Pro Plan - ₹1,999/month (future pricing)
    const proPlan = await razorpay.plans.create({
      period: 'monthly',
      interval: 1,
      item: {
        name: 'BlogCraft AI - Pro',
        description: 'Unlimited AI blog posts with advanced features',
        amount: 199900, // ₹1,999 in paise
        currency: 'INR',
      },
      notes: {
        plan_type: 'pro',
        features: 'unlimited_blogs,priority_support,api_access,white_label',
      },
    })

    console.log('✅ Pro Plan created:')
    console.log(`   Plan ID: ${proPlan.id}`)
    console.log(`   Amount: ₹${proPlan.item.amount / 100}/month`)
    console.log(`   Period: ${proPlan.period}`)
    console.log()

    console.log('🎉 Razorpay plans setup complete!')
    console.log()
    console.log('📝 Add these Plan IDs to your .env.local:')
    console.log(`RAZORPAY_FOUNDER_PLAN_ID=${founderPlan.id}`)
    console.log(`RAZORPAY_PRO_PLAN_ID=${proPlan.id}`)
    console.log()
    console.log('💡 Next steps:')
    console.log('1. Add plan IDs to .env.local')
    console.log('2. Set up webhook URL in Razorpay dashboard')
    console.log('3. Test payment flow')
    console.log('4. Deploy to production')
  } catch (error) {
    console.error('❌ Error setting up plans:', error)
    
    if (error.error?.description) {
      console.error('   Description:', error.error.description)
    }
    
    console.log()
    console.log('💡 Make sure you have:')
    console.log('1. Valid Razorpay API keys in .env.local')
    console.log('2. Active Razorpay account')
    console.log('3. Subscription feature enabled in your account')
  }
}

// Run setup
setupPlans()
